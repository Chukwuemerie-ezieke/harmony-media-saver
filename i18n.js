  function resolveLanguage(setting, browserLanguage = "") {
    if (setting && setting !== "auto" && STRINGS[setting]) return setting;
    const base = String(browserLanguage || "").toLowerCase().split(/[-_]/)[0];
    return STRINGS[base] ? base : "en";
  }

  function translator(language) {
    const table = STRINGS[language] || STRINGS.en;
    return (key, vars = {}) => {
      const text = table[key] ?? STRINGS.en[key] ?? key;
      return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
    };
  }

  // Fill elements marked with data-i18n / data-i18n-title / data-i18n-aria-label.
  function applyTranslations(doc, t) {
    doc.querySelectorAll("[data-i18n]").forEach((node) => {
      node.textContent = t(node.dataset.i18n);
    });
    doc.querySelectorAll("[data-i18n-title]").forEach((node) => {
      node.title = t(node.dataset.i18nTitle);
    });
    doc.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
      node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
    });
  }

  const api = { LANGUAGES, STRINGS, resolveLanguage, translator, applyTranslations };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.HarmonyI18n = api;
